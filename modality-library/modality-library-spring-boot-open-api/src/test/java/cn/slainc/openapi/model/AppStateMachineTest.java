package cn.slainc.openapi.model;

import cn.slainc.core.exception.BizException;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class AppStateMachineTest {

    @Test
    void fullLifecycleTransitions() {
        App app = App.create("订单中心", AppType.WEB, "dev-001");
        assertEquals(AppStatus.DRAFT, app.getStatus());
        assertTrue(app.editable());
        app.transition(AppAction.SUBMIT);
        assertEquals(AppStatus.REVIEWING, app.getStatus());
        assertFalse(app.editable());
        app.transition(AppAction.APPROVE);
        assertEquals(AppStatus.ONLINE, app.getStatus());
        app.transition(AppAction.OFFLINE);
        assertEquals(AppStatus.OFFLINE, app.getStatus());
        app.transition(AppAction.REPUBLISH);
        assertEquals(AppStatus.REVIEWING, app.getStatus());
    }

    @Test
    void rejectReturnsToDraft() {
        App app = App.create("应用", AppType.SERVER, "dev-001");
        app.transition(AppAction.SUBMIT);
        app.transition(AppAction.REJECT);
        assertEquals(AppStatus.DRAFT, app.getStatus());
    }

    @Test
    void illegalTransitionGivesChineseError() {
        App app = App.create("应用", AppType.WEB, "dev-001");
        BizException exception = assertThrows(BizException.class, () -> app.transition(AppAction.APPROVE));
        assertTrue(exception.getMessage().contains("草稿"));
        assertTrue(exception.getMessage().contains("不允许"));

        App online = App.create("应用", AppType.WEB, "dev-001");
        online.transition(AppAction.SUBMIT);
        online.transition(AppAction.APPROVE);
        assertThrows(BizException.class, () -> online.transition(AppAction.SUBMIT));
    }

    @Test
    void createValidatesRequiredFields() {
        assertThrows(BizException.class, () -> App.create(null, AppType.WEB, "dev-001"));
        assertThrows(BizException.class, () -> App.create("应用", null, "dev-001"));
        assertThrows(BizException.class, () -> App.create("应用", AppType.WEB, " "));
    }

    @Test
    void appIdAutoGeneratedWithPrefix() {
        App app = App.create("应用", AppType.DESKTOP, "dev-001");
        assertTrue(app.getAppId().startsWith("app_"));
        assertEquals(20, app.getAppId().length());
    }
}
