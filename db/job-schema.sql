CREATE TABLE IF NOT EXISTS t_job_task (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    tenant_id BIGINT,
    job_name VARCHAR(64) NOT NULL,
    handler_name VARCHAR(128) NOT NULL,
    cron VARCHAR(128),
    params TEXT,
    enabled TINYINT NOT NULL DEFAULT 1,
    status VARCHAR(16) NOT NULL DEFAULT 'RUNNING',
    retry_count INT NOT NULL DEFAULT 0,
    retry_interval INT NOT NULL DEFAULT 0,
    timeout_seconds INT,
    concurrent TINYINT NOT NULL DEFAULT 1,
    misfire_policy VARCHAR(32),
    job_group VARCHAR(64),
    remark VARCHAR(256),
    create_time BIGINT NOT NULL,
    update_time BIGINT NOT NULL,
    CONSTRAINT uk_job_task_tenant_name UNIQUE (tenant_id, job_name),
    KEY idx_job_task_group (job_group),
    KEY idx_job_task_create_time (create_time)
);

CREATE TABLE IF NOT EXISTS t_job_log (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    tenant_id BIGINT,
    job_name VARCHAR(64) NOT NULL,
    attempt INT NOT NULL DEFAULT 0,
    success TINYINT NOT NULL DEFAULT 1,
    status VARCHAR(16) NOT NULL,
    message VARCHAR(2000),
    cost_millis BIGINT NOT NULL DEFAULT 0,
    node_id VARCHAR(64),
    fire_time BIGINT NOT NULL,
    create_time BIGINT NOT NULL,
    KEY idx_job_log_query (tenant_id, create_time),
    KEY idx_job_log_job_time (job_name, create_time),
    KEY idx_job_log_fire_time (fire_time)
);

